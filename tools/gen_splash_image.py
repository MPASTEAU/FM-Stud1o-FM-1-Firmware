"""The power-on splash's picture (run by tools/build.py generate()).

  gen_splash_image.py OUT.h [IMAGE]

IMAGE (default assets/splash.webp) is fitted into SPLASH_SIZE x SPLASH_SIZE (aspect kept, centred on black; nearest
neighbour when it is scaled up by a whole factor, Lanczos otherwise) and written as RGB565, byte-swapped as the
canvas stores pixels (src/gfx.c: the panel takes RGB565 big-endian): SPLASH_W, SPLASH_H, SPLASH_PX[]. No image:
SPLASH_W 0 (ui_draw.c draw_splash draws none).
"""
import sys
from pathlib import Path

SPLASH_SIZE = 128
ROOT = Path(__file__).resolve().parent.parent


def rgb565_swapped(r, g, b):
    v = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
    return (v >> 8 | v << 8) & 0xFFFF


def main():
    out = Path(sys.argv[1])
    src = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "assets" / "splash.webp"
    lines = ["/* generated by tools/gen_splash_image.py: the splash's picture, RGB565 byte-swapped */", "#pragma once"]
    if not src.exists():
        lines += ["#define SPLASH_W 0", "#define SPLASH_H 0", "static const uint16_t SPLASH_PX[1] = {0};"]
        out.write_text("\n".join(lines) + "\n")
        print(f"splash: no {src.name}, none")
        return
    from PIL import Image
    im = Image.open(src).convert("RGB")
    w, h = im.size
    k = min(SPLASH_SIZE / w, SPLASH_SIZE / h)
    nw, nh = max(1, round(w * k)), max(1, round(h * k))
    exact = k >= 1 and k == int(k)
    im = im.resize((nw, nh), Image.NEAREST if exact else Image.LANCZOS)
    canvas = Image.new("RGB", (SPLASH_SIZE, SPLASH_SIZE))
    canvas.paste(im, ((SPLASH_SIZE - nw) // 2, (SPLASH_SIZE - nh) // 2))
    px = [rgb565_swapped(*canvas.getpixel((x, y))) for y in range(SPLASH_SIZE) for x in range(SPLASH_SIZE)]
    lines += [f"#define SPLASH_W {SPLASH_SIZE}", f"#define SPLASH_H {SPLASH_SIZE}",
              f"static const uint16_t SPLASH_PX[{len(px)}] = {{"]
    for i in range(0, len(px), 16):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in px[i:i + 16]) + ",")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"splash: {src.name} {w}x{h} -> {SPLASH_SIZE}x{SPLASH_SIZE}, {len(px) * 2} B -> {out}")


if __name__ == "__main__":
    main()
